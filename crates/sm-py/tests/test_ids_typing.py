"""Acceptance 6: ids, generated stubs (drift) and `mypy --strict` on the typing example."""

from __future__ import annotations

import importlib.util
import pathlib
import subprocess
import sys

import pytest

import smartmesh as sm
from smartmesh import _native
from smartmesh.ids import all_kinds

CRATE = pathlib.Path(__file__).resolve().parents[1]


def test_parse_round_trips_every_kind_and_both_spellings() -> None:
    kinds = all_kinds()
    assert len(kinds) >= 27 and "TopoVolume" in kinds and "MeshCell" in kinds
    for k in kinds:
        e = sm.EntityId.parse(f"{k}#42")
        assert str(e) == f"{k}#42" and e.kind == k and e.serial == 42
        assert sm.EntityId.from_raw(e.raw) == e
        assert sm.EntityId.parse(str(e)) == e
    assert sm.EntityId.parse("Volume#3") == sm.EntityId.parse("TopoVolume#3")  # command-language spelling
    assert str(sm.EntityId.parse("Face#1")) == "TopoFace#1"
    for bad in ["", "TopoVolume", "TopoVolume#", "#1", "Nope#1", "TopoVolume#-1", "TopoVolume#x", "TopoVolume#1 "]:
        with pytest.raises(sm.InvalidParamsError):
            sm.EntityId.parse(bad)
    with pytest.raises(sm.InvalidParamsError):
        sm.EntityId.from_raw(0)


def test_ids_are_frozen_hashable_and_ordered() -> None:
    a, b = sm.EntityId.parse("TopoVertex#9"), sm.EntityId.parse("TopoVolume#1")
    assert a < b and b > a and a <= a and a != b
    assert len({a, sm.EntityId.parse("TopoVertex#9"), b}) == 2
    assert sorted([b, a]) == [a, b]
    with pytest.raises(AttributeError):
        a.serial = 3  # type: ignore[misc]
    assert a.raw == _native.entity_parse("TopoVertex#9")[2]  # type: ignore[index]


def test_ids_from_outputs_can_be_passed_back_unchanged(s: sm.Session) -> None:
    b = s.model.create_brick(x=2.0)
    assert all(isinstance(i, sm.EntityId) for ids in b.outputs.values() for i in ids)
    vol = b.outputs["volume"]
    s.ops.mesh.size(targets=vol, size=1.0)
    s.ops.mesh.scheme(targets=vol, scheme="map")
    r = s.ops.mesh.run(targets=vol)
    assert r.outputs["mesh"][0].kind == "Mesh"
    assert s.query("mesh.info", mesh=r.outputs["mesh"][0])["cells"] == 8
    assert s.q.mesh.info(mesh=str(r.outputs["mesh"][0]))["cells"] == 8
    assert s.query("model.measure", entity="Volume#1")["volume"] == pytest.approx(8.0)
    # Unknown fields stay available on `.extra`/`.raw`.
    assert b.raw["node"] == b.node


def _load_gen() -> object:
    spec = importlib.util.spec_from_file_location("gen_stubs", CRATE / "tools" / "gen_stubs.py")
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_committed_stub_matches_the_live_catalog(s: sm.Session) -> None:
    gen = _load_gen()
    text = gen.generate(s.catalog().raw)  # type: ignore[attr-defined]
    committed = (CRATE / "python" / "smartmesh" / "ops.pyi").read_text()
    assert text == committed, "ops.pyi is stale: run `python tools/gen_stubs.py` (it is a golden, regenerated by W3b-INT)"
    # every op of the catalog (but core.batch) has a stub signature
    for name in s.catalog().ops:
        if not name.startswith("core."):
            assert f"def {name.split('.', 1)[1]}(" in committed, name


def test_runtime_and_stub_agree_on_the_families(s: sm.Session) -> None:
    for name in s.catalog().ops:
        if name.startswith("core."):
            continue
        prefix, short = name.split(".", 1)
        assert callable(getattr(getattr(s.ops, prefix), short))
    assert "create_brick" in dir(s.model) and "run" in dir(s.ops.mesh)
    assert callable(s.q.model.measure)


def test_mypy_strict_accepts_the_example_and_rejects_misspellings(tmp_path: pathlib.Path) -> None:
    def mypy(*args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run([sys.executable, "-m", "mypy", "--strict", "--no-incremental", *args], capture_output=True, text=True, cwd=CRATE)

    ok = mypy("tests/typing_example.py")
    assert ok.returncode == 0, ok.stdout + ok.stderr
    bad = tmp_path / "bad.py"
    bad.write_text(
        "import smartmesh as sm\n"
        "s = sm.Session.memory()\n"
        "s.model.create_brick(widht=1.0)\n"  # misspelled keyword
        "s.model.create_brick(1.0)\n"  # positional
        "s.model.create_brik(x=1.0)\n"  # misspelled op
        "s.ops.mesh.size(targets=[], size='a')\n"  # wrong type
    )
    r = mypy(str(bad))
    assert r.returncode == 1
    assert r.stdout.count("error:") >= 4, r.stdout
