#!/usr/bin/env python3
"""Generate `python/smartmesh/ops.pyi` from the live `catalog` (ops, queries and their JSON Schemas).

    python tools/gen_stubs.py            # rewrite the stub
    python tools/gen_stubs.py --check    # exit 1 if the committed stub differs (the drift check)

The stub is a golden: when another task adds an op, regenerate it (W3b-INT does for the merge).
"""

from __future__ import annotations

import keyword
import pathlib
import sys
from typing import Any

HERE = pathlib.Path(__file__).resolve().parent
STUB = HERE.parent / "python" / "smartmesh" / "ops.pyi"
ENTITY = "EntityId | str"


def _resolve(s: dict[str, Any], root: dict[str, Any]) -> dict[str, Any]:
    ref = s.get("$ref")
    if isinstance(ref, str) and ref.startswith("#/$defs/"):
        return root.get("$defs", {}).get(ref[len("#/$defs/") :], {})
    return s


def _nullable(t: Any) -> bool:
    return isinstance(t, list) and "null" in t


def _join(parts: list[str]) -> str:
    seen: list[str] = []
    for p in parts:
        if p not in seen:
            seen.append(p)
    if "Any" in seen:
        return "Any"
    return " | ".join(seen)


def py_type(s: dict[str, Any], root: dict[str, Any], depth: int = 0) -> str:
    """Python annotation for a JSON Schema node. Loose schemas give `Any`, never a wrong type."""
    if depth > 6:
        return "Any"
    kinds = s.get("x-entity-kind")
    t = s.get("type")
    if kinds:
        is_array = t == "array" or (isinstance(t, list) and "array" in t)
        base = f"Sequence[{ENTITY}]" if is_array else ENTITY
        return f"{base} | None" if _nullable(t) else base
    ref = s.get("$ref")
    if isinstance(ref, str):
        if ref.endswith("/EntityId"):
            return ENTITY
        return py_type(_resolve(s, root), root, depth + 1)
    if "const" in s:
        return f"Literal[{s['const']!r}]"
    if "enum" in s:
        return "Literal[" + ", ".join(repr(v) for v in s["enum"]) + "]"
    for key in ("oneOf", "anyOf"):
        if key in s:
            subs = s[key]
            if all("const" in x for x in subs):
                return "Literal[" + ", ".join(repr(x["const"]) for x in subs) + "]"
            return _join([py_type(x, root, depth + 1) for x in subs])
    if isinstance(t, list):
        return _join([py_type({**s, "type": x}, root, depth + 1) for x in t])
    if t == "string":
        return "str"
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "null":
        return "None"
    if t == "array":
        items = s.get("items")
        return f"Sequence[{py_type(items, root, depth + 1) if isinstance(items, dict) else 'Any'}]"
    if t == "object":
        return "Mapping[str, Any]"
    return "Any"


def _doc(text: str, extra: list[str], indent: str) -> str:
    first = text.strip().split("\n\n")[0].replace("\n", " ").replace("\\", "\\\\").replace('"""', "'''")
    lines = [first] + extra
    body = f"\n{indent}".join(lines)
    return f'{indent}"""{body}"""'


def _signature(name: str, schema: dict[str, Any], ret: str, doc: list[str], text: str) -> list[str]:
    props: dict[str, Any] = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    params: list[str] = []
    needs_kwargs = False
    for pname, ps in props.items():
        if not pname.isidentifier() or keyword.iskeyword(pname):
            needs_kwargs = True
            continue
        ann = py_type(ps, schema)
        params.append(f"{pname}: {ann}" if pname in required else f"{pname}: {ann} = ...")
    if needs_kwargs:
        params.append("**extra: Any")
    sig = ", ".join(["self", "*", *params]) if params else "self"
    out = [f"    def {name}({sig}) -> {ret}:"]
    out.append(_doc(text, doc, "        "))
    return out


def generate(catalog: dict[str, Any]) -> str:
    """The text of `ops.pyi` for a catalog (the `catalog` result JSON)."""
    ops = sorted(catalog["ops"], key=lambda o: o["name"])
    queries = sorted(catalog["queries"], key=lambda q: q["name"])
    lines = [
        '"""Typed op and query signatures, GENERATED by tools/gen_stubs.py from the live catalog. Do not edit."""',
        "",
        "from typing import Any, Literal, Mapping, Sequence",
        "",
        "from .ids import EntityId",
        "from .results import ApplyResult",
        "",
    ]
    by_prefix: dict[str, list[dict[str, Any]]] = {}
    for o in ops:
        prefix, _, short = o["name"].partition(".")
        if prefix == "core":
            continue  # core.batch is `Session.batch()`
        by_prefix.setdefault(prefix, []).append({**o, "short": short})
    for prefix, items in by_prefix.items():
        lines += [f"class {prefix.capitalize()}Ops:", f'    """Ops `{prefix}.*` (keyword-only; `s.ops.{prefix}.<op>(...)` applies one)."""']
        for o in items:
            outs = [
                f"Output `{r['name']}` ({r['cardinality']}, {'/'.join(r['kinds'])}): {r['doc']}" for r in o.get("outputs", [])
            ]
            lines += _signature(o["short"], o["schema"], "ApplyResult", outs, o["schema"].get("description", o["name"]))
            lines.append("")
    qprefix: dict[str, list[dict[str, Any]]] = {}
    for q in queries:
        prefix, _, short = q["name"].partition(".")
        qprefix.setdefault(prefix, []).append({**q, "short": short})
    for prefix, items in qprefix.items():
        lines += [f"class {prefix.capitalize()}Queries:", f'    """Queries `{prefix}.*` (`s.q.{prefix}.<query>(...)`; read-only)."""']
        for q in items:
            lines += _signature(q["short"], q["schema"], "Any", [], q["schema"].get("description", q["name"]))
            lines.append("")
    lines += ["class Ops:", '    """`s.ops.<prefix>`: every op family."""']
    lines += [f"    {p}: {p.capitalize()}Ops" for p in by_prefix]
    lines += ["", "class Queries:", '    """`s.q.<prefix>`: every query family."""']
    lines += [f"    {p}: {p.capitalize()}Queries" for p in qprefix]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    import smartmesh

    text = generate(smartmesh.Session.memory().catalog().raw)
    if "--check" in argv:
        if not STUB.exists() or STUB.read_text() != text:
            print(f"{STUB} is out of date; run tools/gen_stubs.py", file=sys.stderr)
            return 1
        return 0
    STUB.write_text(text)
    print(f"wrote {STUB}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
