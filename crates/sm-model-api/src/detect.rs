//! Symmetry detection from colored invariants.
//!
//! Symmetry is undefined until volumes are colored: a symmetry must map every color to itself.
//! Algorithm (reference implementation, deterministic, bounded):
//!
//! 1. Per-color moments (measure, barycentre, second moment) and the global barycentre `C`.
//! 2. Candidate directions: principal axes of the global inertia, directions of volume barycentres
//!    from `C`, and differences between same-color volume barycentres (capped).
//! 3. Candidate operations through `C` (a symmetry fixes every color barycentre, hence their
//!    weighted mean): a mirror per direction (normal), a rotation of order `2..=max` per direction.
//! 4. **Screening**: the candidate must preserve every color's moments (cheap, O(colors)).
//! 5. **Verification**: map every volume and face individually (moments, area, centroid, normal,
//!    colors, boundary-kind class) onto a distinct image; this is the exact check. O(V² + F²) in
//!    this reference version; a spatial index replaces the linear search later without changing the
//!    API.
//!
//! Translations are not detected: a finite model has no translation symmetry. Declare periodicity
//! with a slab cut instead.

use crate::boundary::{BoundaryKind, BoundaryTable};
use crate::coloring::Coloring;
use crate::error::{ModelError, Result};
use crate::group::{DeckKind, DeckOp, DeckGroup, DeckGenerator};
use crate::topo::{GeometryView, Moments};
use crate::xf::{Axis, Plane, Tolerance, Turns, eigen_symmetric};
use sm_core::{EntityId, EntityKind, Point3, Vector3};
use std::collections::BTreeMap;

/// Detection parameters.
#[derive(Clone, Debug)]
pub struct DetectParams {
    /// Tolerances for screening and verification.
    pub tol: Tolerance,
    /// Largest rotation order tried.
    pub max_rotation_order: u32,
    /// Cap on candidate directions (principal axes always kept).
    pub max_directions: usize,
    /// Cap on same-color volume pairs used to propose directions.
    pub max_pairs: usize,
}

impl Default for DetectParams {
    fn default() -> Self {
        Self { tol: Tolerance { linear: 1e-9, relative: 1e-7, angular: 1e-7 }, max_rotation_order: 12, max_directions: 64, max_pairs: 256 }
    }
}

/// Why a candidate failed verification.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub enum RejectReason {
    /// No same-color volume matches the image of this volume.
    VolumeNotMapped(EntityId),
    /// No face with the same color, kind class and geometry matches the image of this face.
    FaceNotMapped(EntityId),
}

/// Verification status of a candidate.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub enum Verification {
    /// Declared only; never checked against the model.
    Unchecked,
    /// Passed screening, failed the exact check.
    Rejected(RejectReason),
    /// Every volume and face maps onto a distinct image with matching colors and kinds.
    Verified {
        /// Volumes mapped.
        volumes: usize,
        /// Faces mapped.
        faces: usize,
    },
}

/// A detected candidate operation.
#[derive(Clone, Debug, PartialEq)]
pub struct Candidate {
    /// The operation (through the global barycentre).
    pub op: DeckOp,
    /// Order of the cyclic group it generates.
    pub order: u32,
    /// Verification status.
    pub verification: Verification,
}

impl Candidate {
    /// Make a generator for this candidate (allocating its `Boundary` id) to build a `Full`-state
    /// [`crate::symmetry::Symmetry`] from.
    pub fn into_generator(&self, ids: &mut dyn crate::ids::IdAllocator) -> DeckGenerator {
        DeckGenerator { id: ids.alloc(EntityKind::Boundary), op: self.op }
    }
}

/// Detection result.
#[derive(Clone, Debug)]
pub struct DetectionReport {
    /// Global barycentre of all colored volumes.
    pub centroid: Point3,
    /// Principal axes of the global inertia (descending eigenvalue).
    pub principal_axes: [Vector3; 3],
    /// Candidates in canonical order: verified first, then mirrors before rotations, then by order
    /// and direction.
    pub candidates: Vec<Candidate>,
    /// Number of proposals discarded by screening.
    pub screened_out: usize,
}

impl DetectionReport {
    /// Verified candidates only.
    pub fn verified(&self) -> impl Iterator<Item = &Candidate> {
        self.candidates.iter().filter(|c| matches!(c.verification, Verification::Verified { .. }))
    }

    /// Order of the group generated by all verified candidates, if it closes.
    pub fn verified_group_order(&self, ids: &mut dyn crate::ids::IdAllocator) -> Result<usize> {
        let gens: Vec<DeckGenerator> = self.verified().map(|c| c.into_generator(ids)).collect();
        Ok(DeckGroup::generate(&gens)?.order())
    }
}

fn kind_class(b: Option<&BoundaryTable>, f: EntityId) -> u8 {
    match b.and_then(|t| t.kind_of(f)) {
        None => 0,
        Some(BoundaryKind::Deck { .. }) => 1,
        Some(BoundaryKind::Response) => 2,
        Some(BoundaryKind::Interface(_)) => 3,
    }
}

fn add_dir(dirs: &mut Vec<Vector3>, v: Vector3, cap: usize) {
    let n = v.norm();
    if n < 1e-9 || dirs.len() >= cap {
        return;
    }
    let u = crate::xf::canonical_sign(v * (1.0 / n));
    if dirs.iter().any(|d| d.cross(u).norm() < 1e-7) {
        return;
    }
    dirs.push(u);
}

/// Detect candidate mirror planes and rotation axes of the colored model.
pub fn detect(
    topo: &dyn GeometryView,
    coloring: &Coloring,
    boundaries: Option<&BoundaryTable>,
    params: &DetectParams,
) -> Result<DetectionReport> {
    let tol = &params.tol;
    let volumes = topo.volumes();
    if volumes.is_empty() {
        return Err(ModelError::Invalid("no volumes".into()));
    }
    let mut vm: Vec<(EntityId, EntityId, Moments)> = Vec::with_capacity(volumes.len());
    let mut per_color: BTreeMap<EntityId, Moments> = BTreeMap::new();
    let mut total = Moments::ZERO;
    for &v in &volumes {
        let c = coloring.volume_color(v).ok_or_else(|| ModelError::Invalid(format!("volume {v} is uncolored; symmetry needs a coloring")))?;
        let m = topo.volume_moments(v).ok_or(ModelError::UnknownEntity(v))?;
        per_color.entry(c).and_modify(|a| *a = a.add(&m)).or_insert(m);
        total = total.add(&m);
        vm.push((v, c, m));
    }
    let c0 = total.centroid;
    let jt = total.second_about(c0);
    let (_, axes) = eigen_symmetric(&jt);

    // Candidate directions, fixed insertion order.
    let cap = params.max_directions.max(3);
    let mut dirs: Vec<Vector3> = Vec::new();
    for a in axes {
        add_dir(&mut dirs, a, cap);
    }
    for (_, _, m) in &vm {
        add_dir(&mut dirs, m.centroid - c0, cap);
    }
    let mut pairs = 0usize;
    'outer: for i in 0..vm.len() {
        for j in (i + 1)..vm.len() {
            if vm[i].1 != vm[j].1 {
                continue;
            }
            if pairs >= params.max_pairs {
                break 'outer;
            }
            pairs += 1;
            add_dir(&mut dirs, vm[i].2.centroid - vm[j].2.centroid, cap);
            add_dir(&mut dirs, (vm[i].2.centroid - c0).cross(vm[j].2.centroid - c0), cap);
        }
    }

    let mut proposals: Vec<DeckOp> = Vec::new();
    for &d in &dirs {
        if let Ok(plane) = Plane::new(c0, d) {
            proposals.push(DeckOp::Mirror { plane });
        }
        if let Ok(axis) = Axis::new(c0, d) {
            for n in 2..=params.max_rotation_order.max(2) {
                if let Ok(turns) = Turns::one_over(n) {
                    proposals.push(DeckOp::Rotation { axis, turns });
                }
            }
        }
    }

    let mut candidates = Vec::new();
    let mut screened_out = 0usize;
    for op in proposals {
        let x = op.transform();
        let ok = per_color.values().all(|m| m.transformed(&x).approx_eq(m, tol));
        if !ok {
            screened_out += 1;
            continue;
        }
        let verification = verify(topo, coloring, boundaries, &vm, &op, tol);
        let order = op.order().unwrap_or(0);
        candidates.push(Candidate { op, order, verification });
    }
    candidates.sort_by_key(sort_key);
    Ok(DetectionReport { centroid: c0, principal_axes: axes, candidates, screened_out })
}

fn sort_key(c: &Candidate) -> (u8, u8, u32, [i64; 3]) {
    let rank = match c.verification {
        Verification::Verified { .. } => 0,
        Verification::Unchecked => 1,
        Verification::Rejected(_) => 2,
    };
    let (kind, d) = match c.op {
        DeckOp::Mirror { plane } => (0u8, plane.normal()),
        DeckOp::Rotation { axis, .. } => (1u8, axis.dir()),
        DeckOp::Translation { vector, .. } => (2u8, vector),
    };
    debug_assert!(matches!(c.op.kind(), DeckKind::Mirror | DeckKind::Rotation | DeckKind::Translation));
    let q = |x: f64| (x * 1e6).round() as i64;
    (rank, kind, c.order, [q(d.x), q(d.y), q(d.z)])
}

fn verify(
    topo: &dyn GeometryView,
    coloring: &Coloring,
    boundaries: Option<&BoundaryTable>,
    vm: &[(EntityId, EntityId, Moments)],
    op: &DeckOp,
    tol: &Tolerance,
) -> Verification {
    let x = op.transform();
    let mut used = vec![false; vm.len()];
    for (v, c, m) in vm {
        let img = m.transformed(&x);
        let hit = vm.iter().enumerate().find(|(k, (_, c2, m2))| !used[*k] && c2 == c && m2.approx_eq(&img, tol));
        match hit {
            Some((k, _)) => used[k] = true,
            None => return Verification::Rejected(RejectReason::VolumeNotMapped(*v)),
        }
    }
    let faces = topo.faces();
    let mut fused = vec![false; faces.len()];
    for (i, &f) in faces.iter().enumerate() {
        let (Some(c), Some(a), Some(n)) = (topo.face_centroid(f), topo.face_area(f), topo.face_normal(f)) else {
            return Verification::Rejected(RejectReason::FaceNotMapped(f));
        };
        let (ci, ni) = (x.apply_point(c), x.apply_vector(n));
        let boundary = topo.face_sides(f).is_some_and(|s| s.is_boundary());
        let hit = faces.iter().enumerate().find(|&(k, &g)| {
            if fused[k] || coloring.face_color(g) != coloring.face_color(f) || kind_class(boundaries, g) != kind_class(boundaries, f) {
                return false;
            }
            let (Some(gc), Some(ga), Some(gn)) = (topo.face_centroid(g), topo.face_area(g), topo.face_normal(g)) else { return false };
            let normal_ok = if boundary { (gn - ni).norm() <= tol.angular } else { gn.cross(ni).norm() <= tol.angular };
            normal_ok && (gc - ci).norm() <= tol.linear + tol.relative * 10.0 && tol.close(a, ga)
        });
        match hit {
            Some((k, _)) => fused[k] = true,
            None => return Verification::Rejected(RejectReason::FaceNotMapped(f)),
        }
        let _ = i;
    }
    Verification::Verified { volumes: vm.len(), faces: faces.len() }
}
