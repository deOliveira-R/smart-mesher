//! Typed errors for the model-semantics layer.

use sm_core::{EntityId, EntityKind};
use sm_topo_api::QueryError;

/// Everything that can go wrong when editing or deriving from the model tables.
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
#[non_exhaustive]
pub enum ModelError {
    /// An id was used that is not present in the relevant table.
    #[error("unknown entity {0}")]
    Unknown(EntityId),
    /// An id had the wrong [`EntityKind`] for the slot it was used in.
    #[error("entity {id} has kind {found:?}, expected {expected:?}")]
    WrongKind {
        /// Offending id.
        id: EntityId,
        /// Kind the slot requires.
        expected: EntityKind,
        /// Kind the id actually has.
        found: EntityKind,
    },
    /// A color of the wrong domain (volume vs face) was used.
    #[error("color {0} has the wrong domain for this use")]
    ColorDomain(EntityId),
    /// The numeric label is already used by another color of the same domain.
    #[error("label {label} is already used in this domain")]
    LabelTaken {
        /// The label.
        label: u32,
    },
    /// The name is already used.
    #[error("name {0:?} is already used")]
    NameTaken(String),
    /// The color is still used by volumes and cannot be removed.
    #[error("color {0} is still used by volumes")]
    ColorInUse(EntityId),
    /// An entity already has a conflicting assignment.
    #[error("{0} is already assigned")]
    Duplicate(EntityId),
    /// The point group generated by the declared decks does not close (infinite or larger than
    /// the element budget). Parallel mirrors compose to a translation and land here.
    #[error("point group is not finite (more than {limit} elements)")]
    GroupNotFinite {
        /// The element budget that was exceeded.
        limit: usize,
    },
    /// A translation generator needs an explicit repeat count to unfold.
    #[error("generator {0} is a translation and needs an explicit repeat count")]
    MissingRepeats(EntityId),
    /// A transform could not be inverted.
    #[error("transform is singular")]
    Singular,
    /// A prototype/lattice/group reference cycle.
    #[error("reference cycle through {0}")]
    Cycle(EntityId),
    /// A structurally invalid request, with an explanation.
    #[error("invalid request: {0}")]
    Invalid(String),
    /// The operation needs a symmetry to be declared first.
    #[error("no symmetry declared")]
    NoSymmetry,
    /// The 56-bit serial space of a kind is exhausted.
    #[error("id space exhausted for {0:?}")]
    IdExhausted(EntityKind),
    /// A topology query failed (unsupported geometry, unknown cell, ...).
    #[error(transparent)]
    Topology(#[from] QueryError),
    /// The kernel's cut result does not match the plan (caps off the planes, kept volumes in the
    /// wrong half-space, deck mates that cannot be re-paired, ...).
    #[error("cut outcome rejected: {0}")]
    CutInvalid(String),
    /// A detected candidate was not verified and `force` was not set.
    #[error("candidate is not verified")]
    Unverified,
    /// The decomposition of this volume must be undone before its topology changes.
    #[error("volume {0} is decomposed; undo the decomposition before changing its topology")]
    DecompositionActive(EntityId),
}

/// Result alias for this crate.
pub type Result<T> = core::result::Result<T, ModelError>;

pub(crate) fn expect_kind(id: EntityId, expected: EntityKind) -> Result<()> {
    if id.kind() == expected { Ok(()) } else { Err(ModelError::WrongKind { id, expected, found: id.kind() }) }
}
